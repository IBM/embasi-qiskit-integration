def test_build_pyscf_mol(tmp_path: Path):
    """The Mole carries the geometry, and PySCF's own max_memory default."""
    atom_str, _ = geometry.parse_xyz_atoms_and_metadata(_write(tmp_path, "meoh.xyz", METHANOL))
    mol = geometry.build_pyscf_mol(atom_str, basis="sto-3g", verbose=0)

    assert mol.natm == 6
    assert mol.nao == 14
    assert mol.nelec == (9, 9)  # neutral methanol: 18 electrons
    assert mol.charge == 0
    # Not the 120 GB the module used to hard-code.
    assert mol.max_memory < 100_000


def test_charge_shifts_electron_count(tmp_path: Path):
    """A net charge must reach the Mole: it is what makes nelec right."""
    atom_str, _ = geometry.parse_xyz_atoms_and_metadata(_write(tmp_path, "meoh.xyz", METHANOL))
    cation = geometry.build_pyscf_mol(atom_str, basis="sto-3g", charge=1, spin=1, verbose=0)
    assert sum(cation.nelec) == 17
    assert cation.charge == 1


def test_read_mol_from_xyz_uses_metadata_charge(tmp_path: Path):
    """The one-shot path derives the charge from the file rather than assuming 0."""
    text = METHANOL.replace("smiles=CO; charge=0", "charge=-1").replace("6\n", "6\n", 1)
    mol = geometry.read_mol_from_xyz(
        _write(tmp_path, "anion.xyz", text), basis="sto-3g", spin=1, verbose=0
    )
    assert mol.charge == -1
    assert sum(mol.nelec) == 19


def test_charge_override_beats_metadata(tmp_path: Path):
    """``charge_override`` wins, for files whose metadata is wrong or missing."""
    mol = geometry.read_mol_from_xyz(
        _write(tmp_path, "meoh.xyz", METHANOL),
        basis="sto-3g",
        charge_override=1,
        spin=1,
        verbose=0,
    )
    assert mol.charge == 1


def test_read_xyz_is_the_shared_front_door(tmp_path: Path):
    """``read_xyz`` resolves geometry + charge once, for every consumer.

    Both readers and ``make_test_data._build_mol`` go through it, so a given file
    can only be read one way -- there is no second charge-resolution path that
    could drift from this one.
    """
    path = _write(tmp_path, "meoh.xyz", METHANOL)
    atom_str, charge, smiles = geometry.read_xyz(path)

    assert len(atom_str.splitlines()) == 6
    assert charge == 0
    assert smiles == "CO"
    # Same atom block the low-level parser produces.
    assert atom_str == geometry.parse_xyz_atoms_and_metadata(path)[0]


def test_read_xyz_override(tmp_path: Path):
    """``charge_override`` short-circuits derivation but keeps the SMILES."""
    text = METHANOL.replace("charge=0", "charge=-1")
    _, charge, smiles = geometry.read_xyz(_write(tmp_path, "anion.xyz", text), charge_override=2)
    assert charge == 2
    assert smiles == "CO"


def test_readers_agree_on_charge(tmp_path: Path):
    """The Mole and Atoms readers cannot disagree, since both delegate to read_xyz."""
    pytest.importorskip("ase", reason="needs the 'embed' extra")
    text = METHANOL.replace("smiles=CO; charge=0", "charge=-1")
    path = _write(tmp_path, "anion.xyz", text)

    mol = geometry.read_mol_from_xyz(path, basis="sto-3g", spin=1, verbose=0)
    _, atoms_charge, _ = geometry.read_atoms_from_xyz(path)
    assert mol.charge == atoms_charge == -1


def test_read_atoms_from_xyz(tmp_path: Path):
    """The ASE bridge returns Atoms in Angstrom plus the derived charge."""
    pytest.importorskip("ase", reason="needs the 'embed' extra")
    atoms, charge, smiles = geometry.read_atoms_from_xyz(_write(tmp_path, "meoh.xyz", METHANOL))

    assert list(atoms.symbols) == ["C", "O", "H", "H", "H", "H"]
    assert atoms.positions[1] == pytest.approx([1.427, 0.0, 0.0])
    assert charge == 0
    assert smiles == "CO"


def test_committed_methanol_fixture_is_readable(data_dir: Path):
    """The committed fixture stays parseable and neutral (used by the workflows)."""
    mol = geometry.read_mol_from_xyz(data_dir / "methanol.xyz", basis="sto-3g", verbose=0)
    assert mol.natm == 6
    assert mol.charge == 0
    assert mol.nelec == (9, 9)
